pub fn escape(config: &Config, rust_identifier: &mut String) {
    if config.language == Language::Nim {
        if NIM_RESERVED_KEYWORDS
            .binary_search(&rust_identifier.as_ref())
            .is_ok()
        {
            rust_identifier.push('x');
        }
        if rust_identifier.starts_with('_') {
            rust_identifier.insert(0, 'x');
        }
    } else if C_RESERVED_KEYWORDS
        .binary_search(&rust_identifier.as_ref())
        .is_ok()
    {
        rust_identifier.push('_');
    }
}

pub fn escaped(config: &Config, rust_identifier: &str) -> String {
    let mut ret = rust_identifier.to_string();
    escape(config, &mut ret);
    ret
}
